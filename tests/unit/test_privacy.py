"""No real WhatsApp identifier or phone number in any versioned file.

The repository is public and five real people use the bot. Every file git
tracks is read (what `git ls-files` lists is what reaches GitHub; .env,
bridge/auth/ and node_modules/ are not tracked, so they are not read).

Fakes have one shape: a two-digit prefix, then only zeros, then at most two
digits to tell people apart: 5500000000001, 100000000000001@lid,
120000000000000001@g.us. A new fixture written that way passes; a real
identifier, with its digits spread out, does not.

Not read: uv.lock and package-lock.json, generated by the tools and made of
package names, versions and hashes, where a run of digits inside a hash looks
like a phone number. Not caught, on purpose: a bare LID without its @lid is
just a long run of digits, like a timestamp in milliseconds.
"""

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

SERVERS = r"s\.whatsapp\.net|lid|g\.us|c\.us|broadcast|newsletter"
# 5500000000001@s.whatsapp.net, 100000000000009:17@lid, 120000000000000001@g.us
JID = re.compile(rf"(?<!\d)(\d{{5,}})(?::\d+)?@(?:{SERVERS})\b")
# A Brazilian phone, bare (5500000000001) or written out (+55 (00) 00000-0001).
PHONE = re.compile(r"(?<!\d)55\d{10,11}(?!\d)")
WRITTEN_PHONE = re.compile(r"\+55[\s(]*\d{2}[\s)]*\d{4,5}[\s-]?\d{4}(?!\d)")
FAKE = re.compile(r"\d{2}0+\d{0,2}")
LOCK_FILES = {"uv.lock", "package-lock.json"}


def is_fake(digits: str) -> bool:
    return FAKE.fullmatch(digits) is not None


def real_identifiers(text: str) -> list[str]:
    """Every identifier in text that is not one of the fakes."""
    found = [m[1] for m in JID.finditer(text)]
    found += [m[0] for m in PHONE.finditer(text)]
    found += [re.sub(r"\D", "", m[0]) for m in WRITTEN_PHONE.finditer(text)]
    real = [digits for digits in found if not is_fake(digits)]
    return list(dict.fromkeys(real))  # a phone JID matches two rules: count it once


def versioned_files() -> list[Path]:
    names = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True
    ).stdout.split(b"\0")
    return [ROOT / name.decode() for name in names if name]


def test_no_versioned_file_holds_a_real_identifier():
    offenders = {}
    for path in versioned_files():
        if not path.is_file() or path.name in LOCK_FILES:
            continue  # deleted but not yet committed; or generated hashes
        content = path.read_bytes()
        if b"\0" in content:
            continue  # binary
        found = real_identifiers(content.decode("utf-8", errors="ignore"))
        if found:
            # Report where, never what: the point is not to print them.
            offenders[str(path.relative_to(ROOT))] = len(found)

    assert offenders == {}


def test_the_fixtures_fakes_pass():
    assert (
        real_identifiers(
            "5500000000001@s.whatsapp.net 100000000000009:17@lid "
            "120000000000000001@g.us BRIDGE_PAIRING_PHONE=5500000000000 "
            "+55 (00) 0000-0000"
        )
        == []
    )


def test_real_looking_identifiers_are_caught():
    # Assembled at run time, so no real-looking identifier sits in this file.
    phone = "55" + "55" + "9" + "8765" + "4321"
    lid = "13" + "5792468" + "024680"
    group = "1987" + "6543" + "2109" + "8765"

    assert real_identifiers(f"{phone}@s.whatsapp.net") == [phone]
    assert real_identifiers(f"from {lid}:4@lid") == [lid]
    assert real_identifiers(f"{group}@g.us") == [group]
    assert real_identifiers(f"PHONE={phone}") == [phone]
    assert real_identifiers("+55 (" + "55) 9" + "8765-4321") == [phone]
